/// TricoreDAGToDAGISel - Tricore specific code to select Tricore machine
/// instructions for SelectionDAG operations.
///
namespace {
class TricoreDAGToDAGISel : public SelectionDAGISel {
  /// Subtarget - Keep a pointer to the Tricore Subtarget around so that we can
  /// make the right decision when generating code for different targets.
  const TricoreSubtarget *Subtarget = nullptr;

public:
  TricoreDAGToDAGISel() = delete;

  explicit TricoreDAGToDAGISel(TricoreTargetMachine &tm)
      : SelectionDAGISel(tm) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<TricoreSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *N) override;

  bool SelectAddrFrameIndex(SDValue N, SDValue &Base, SDValue &Offset);
  bool SelectAddrRegImmBO(SDValue N, SDValue &Base, SDValue &Offset);
  bool SelectAddrRegImmBOL(SDValue N, SDValue &Base, SDValue &Offset);

  // Include the pieces autogenerated from the target description.
#include "TricoreGenDAGISel.inc"
};

class TricoreDAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;
  explicit TricoreDAGToDAGISelLegacy(TricoreTargetMachine &tm)
      : SelectionDAGISelLegacy(ID, std::make_unique<TricoreDAGToDAGISel>(tm)) {}
};
} // end anonymous namespace

