bool TricoreDAGToDAGISel::SelectAddrFrameIndex(SDValue Addr, SDValue &Base,
                                               SDValue &Offset) {
  if (auto *FIN = dyn_cast<FrameIndexSDNode>(Addr)) {
    Base = CurDAG->getTargetFrameIndex(FIN->getIndex(), MVT::i32);
    Offset = CurDAG->getTargetConstant(0, SDLoc(Addr), MVT::i32);
    return true;
  }

  return false;
}

bool TricoreDAGToDAGISel::SelectAddrRegImmBO(SDValue Addr, SDValue &Base,
                                           SDValue &Offset) {
  SDLoc DL(Addr);
  MVT VT = Addr.getSimpleValueType();

  if (SelectAddrFrameIndex(Addr, Base, Offset))
    return true;

  if (CurDAG->isBaseWithConstantOffset(Addr)) {
    int64_t CVal = cast<ConstantSDNode>(Addr.getOperand(1))->getSExtValue();
    if (isInt<12>(CVal)) {
      Base = Addr.getOperand(0);
      Offset = CurDAG->getSignedTargetConstant(CVal, DL, VT);
      return true;
    }
  }

  Base = Addr;
  Offset = CurDAG->getTargetConstant(0, DL, VT);

  return true;
}

bool TricoreDAGToDAGISel::SelectAddrRegImmBOL(SDValue Addr, SDValue &Base,
                                           SDValue &Offset) {
  SDLoc DL(Addr);
  MVT VT = Addr.getSimpleValueType();

  if (SelectAddrFrameIndex(Addr, Base, Offset))
    return true;

  if (CurDAG->isBaseWithConstantOffset(Addr)) {
    int64_t CVal = cast<ConstantSDNode>(Addr.getOperand(1))->getSExtValue();
    if (isInt<16>(CVal)) {
      Base = Addr.getOperand(0);
      Offset = CurDAG->getSignedTargetConstant(CVal, DL, VT);
      return true;
    }
  }

  Base = Addr;
  Offset = CurDAG->getTargetConstant(0, DL, VT);

  return true;
}

/// createTricoreISelDag - This pass converts a legalized DAG into a
/// Tricore-specific DAG, ready for instruction scheduling.
///
FunctionPass *llvm::createTricoreISelDag(TricoreTargetMachine &TM) {
  return new TricoreDAGToDAGISelLegacy(TM);
}
