#ifndef LLVM_LIB_TARGET_TRICORE_TRICORESUBTARGET_H
#define LLVM_LIB_TARGET_TRICORE_TRICORESUBTARGET_H

#include "MCTargetDesc/TricoreMCTargetDesc.h"
#include "TricoreFrameLowering.h"
#include "TricoreISelLowering.h"
#include "TricoreInstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Support/ErrorHandling.h"
#include "llvm/TargetParser/Triple.h"

#define GET_SUBTARGETINFO_HEADER
#include "TricoreGenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class TricoreSubtarget : public TricoreGenSubtargetInfo {
  // ReserveRegister[i] - Register #i is not available as a general purpose
  // register.
  BitVector ReserveRegister;

  Triple TargetTriple;
  virtual void anchor();

  TricoreInstrInfo InstrInfo;
  TricoreTargetLowering TLInfo;
  SelectionDAGTargetInfo TSInfo;
  TricoreFrameLowering FrameLowering;

  enum FPType { FP_Soft, FP_Single, FP_Double };
  enum TricoreArchType { TC13, TC131, TC16, TC162, TC18 };
  
  enum FPType FPType = FP_Soft;
  enum TricoreArchType ArchType = TC13;

#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "TricoreGenSubtargetInfo.inc"

public:
  TricoreSubtarget(const StringRef &CPU, const StringRef &TuneCPU,
                   const StringRef &FS, const TargetMachine &TM);

  const TricoreInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const TricoreRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const TricoreTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  bool enableMachineScheduler() const override;

#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool GETTER() const { return ATTRIBUTE; }
#include "TricoreGenSubtargetInfo.inc"

  bool hasSoftFloat() const { return FPType == FP_Soft; }
  bool hasSingleFloat() const { return FPType == FP_Single; }
  bool hasDoubleFloat() const { return FPType == FP_Double; }

  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
  TricoreSubtarget &initializeSubtargetDependencies(StringRef CPU,
                                                    StringRef TuneCPU,
                                                    StringRef FS);

  bool isRegisterReserved(MCPhysReg PhysReg) const {
    return ReserveRegister[PhysReg];
  }
};

} // end namespace llvm

#endif
